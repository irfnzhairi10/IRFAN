"""Procedural soundtrack + SFX + VO mix. Usage: python scripts/make_audio.py <vo_source.mov>
Everything except the supplied VO is generated by code (no samples, no copied music)."""
import sys, json, subprocess, numpy as np
from scipy import signal
from scipy.io import wavfile

SR = 44100
DUR = 65.667
N = int(SR * DUR)
rng = np.random.default_rng(7)
tl = json.load(open('src/timeline.json'))
src = sys.argv[1]

# ---------- VO: extract, clean, normalise ----------
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', src, '-vn', '-ac', '1', '-ar', str(SR),
                '-af', 'highpass=f=90,acompressor=threshold=-24dB:ratio=3:attack=8:release=120,loudnorm=I=-15:TP=-2:LRA=7',
                'assets/vo_clean.wav'], check=True)
sr, vo = wavfile.read('assets/vo_clean.wav')
vo = vo.astype(np.float32) / (32768 if vo.dtype == np.int16 else 1)
VO = np.zeros(N, np.float32); VO[:min(N, len(vo))] = vo[:N]

def t_axis(n): return np.arange(n) / SR
def place(buf, x, t0):
    i = int(t0 * SR); 
    if i < 0: x = x[-i:]; i = 0
    j = min(N, i + len(x))
    if j > i: buf[i:j] += x[:j - i]
def env_exp(n, tau): return np.exp(-t_axis(n) / tau)
def lp(x, f, o=2): return signal.sosfilt(signal.butter(o, f, 'low', fs=SR, output='sos'), x)
def hp(x, f, o=2): return signal.sosfilt(signal.butter(o, f, 'high', fs=SR, output='sos'), x)
def bp(x, a, b, o=2): return signal.sosfilt(signal.butter(o, [a, b], 'band', fs=SR, output='sos'), x)
def midi(m): return 440 * 2 ** ((m - 69) / 12)

# ---------- SFX ----------
def noise(n): return rng.standard_normal(n).astype(np.float32)
def sweep_noise(dur, f0, f1, shape='bell', q=0.35):
    n = int(dur * SR); x = noise(n); out = np.zeros(n, np.float32)
    blocks = 40; bl = n // blocks
    for b in range(blocks):
        fc = f0 * (f1 / f0) ** (b / (blocks - 1))
        seg = x[b * bl:(b + 1) * bl if b < blocks - 1 else n]
        out[b * bl:b * bl + len(seg)] = bp(seg, fc * (1 - q), min(fc * (1 + q), SR * 0.45), 2)
    tt = np.linspace(0, 1, n)
    a = np.sin(np.pi * tt) ** 1.5 if shape == 'bell' else tt ** 2.2
    return out * a
def whoosh(): return sweep_noise(0.7, 350, 5200) * 0.9
def swoosh(): return sweep_noise(1.4, 500, 3000, q=0.5) * 0.5
def pop():
    n = int(0.12 * SR); t = t_axis(n)
    f = 520 * np.exp(-t * 14) + 260
    return (np.sin(2 * np.pi * np.cumsum(f) / SR) * env_exp(n, 0.035) * 0.9 + hp(noise(n), 3000) * env_exp(n, 0.006) * 0.15).astype(np.float32)
def click():
    n = int(0.05 * SR)
    return (bp(noise(n), 2500, 7000) * env_exp(n, 0.008) * 0.45 + np.sin(2 * np.pi * 1700 * t_axis(n)) * env_exp(n, 0.01) * 0.12).astype(np.float32)
def impact():
    n = int(1.6 * SR); t = t_axis(n)
    sub = np.sin(2 * np.pi * np.cumsum(48 + 70 * np.exp(-t * 9)) / SR) * env_exp(n, 0.45)
    hit = lp(noise(n), 1400) * env_exp(n, 0.12) * 0.55
    tail = bp(noise(n), 200, 900) * env_exp(n, 0.5) * 0.2
    return ((sub * 0.95 + hit + tail)).astype(np.float32)
def riser(dur):
    return (sweep_noise(dur, 300, 7000, 'ramp', 0.4) * 0.55).astype(np.float32)
def shimmer():
    n = int(2.2 * SR); out = np.zeros(n, np.float32); t = t_axis(n)
    for k, m in enumerate([86, 90, 93, 98, 101]):  # D hijaz-ish high bells
        d = k * 0.07; tt = np.clip(t - d, 0, None)
        out += (np.sin(2 * np.pi * midi(m) * t) * np.exp(-tt / 0.7) * (t > d)).astype(np.float32) * 0.18
    return out
SFX = {'whoosh': (whoosh, 0.55, -0.35), 'swoosh': (swoosh, 0.5, -0.2), 'pop': (pop, 0.7, 0), 'click': (click, 0.6, 0),
       'impact': (impact, 0.9, 0), 'shimmer': (shimmer, 0.7, 0)}
sfx = np.zeros(N, np.float32)
for t0, kind in tl['cues']:
    if kind in SFX:
        f, g, off = SFX[kind]; place(sfx, f() * g, t0 + off)
    elif kind == 'riser0': place(sfx, riser(3.0) * 0.6, t0)
    elif kind == 'riser1': place(sfx, riser(1.5) * 0.55, t0)
    elif kind == 'riser2': place(sfx, riser(0.8) * 0.5, t0)

# ---------- Music: D hijaz, original ----------
HIJAZ = [0, 1, 4, 5, 7, 8, 10]  # D Eb F# G A Bb C
def pluck(freq, dur=0.9, bright=1.0):
    n = int(dur * SR); t = t_axis(n)
    x = sum(np.sin(2 * np.pi * freq * k * t) * (0.5 ** (k - 1)) * np.exp(-t * (5 + 3 * k)) for k in (1, 2, 3, 4))
    return (x * 0.5).astype(np.float32)
def pad_note(freq, dur):
    n = int(dur * SR); t = t_axis(n)
    x = np.zeros(n)
    for det in (-0.004, 0, 0.004):
        x += signal.sawtooth(2 * np.pi * freq * (1 + det) * t) * 0.18
    x = lp(x.astype(np.float32), 900)
    a = np.minimum(1, t / 1.5) * np.minimum(1, (dur - t) / 1.5)
    return (x * a).astype(np.float32)
def drum_low():
    n = int(0.45 * SR); t = t_axis(n)
    return (np.sin(2 * np.pi * np.cumsum(95 * np.exp(-t * 11) + 52) / SR) * env_exp(n, 0.14) + lp(noise(n), 500) * env_exp(n, 0.03) * 0.25).astype(np.float32)
def drum_tek():
    n = int(0.12 * SR)
    return (bp(noise(n), 1800, 5000) * env_exp(n, 0.03) * 0.5).astype(np.float32)

mus = np.zeros(N, np.float32)
BPM = 96; beat = 60 / BPM
# section map: (start, end, pad_root_midis, arp_level, perc_level)
sections = [
    (0.0, 3.2, [38, 45], 0.0, 0.0),
    (3.2, 16.3, [38, 45, 50], 0.55, 0.0),
    (16.3, 28.3, [38, 45, 50], 0.7, 0.55),
    (28.3, 42.3, [38, 45, 50], 0.55, 0.8),
    (42.3, 49.4, [38, 39, 45], 0.25, 0.0),      # darker: semitone drone, no beat
    (49.4, 54.6, [38, 45, 50], 0.5, 0.5),
    (54.6, 62.0, [38, 45, 54, 57], 0.9, 0.9),   # warm, resolved (F#/A in chord)
    (62.0, 65.667, [38, 45, 54], 0.5, 0.0),
]
for a, b, notes, arp, perc in sections:
    for m in notes:
        place(mus, pad_note(midi(m), b - a + 1.0) * 0.5, a)
    if arp > 0:
        step = beat / 2; k = 0
        t0 = a
        pattern = [0, 2, 4, 2, 5, 4, 2, 1, 0, 2, 4, 6, 5, 4, 2, 0]
        while t0 < b - 0.05:
            deg = pattern[k % len(pattern)]
            midi_n = 62 + HIJAZ[deg % 7] + (12 if deg >= 5 else 0)
            place(mus, pluck(midi(midi_n)) * arp * 0.6, t0)
            t0 += step; k += 1
    if perc > 0:
        t0 = a
        k = 0
        while t0 < b - 0.05:
            if k % 4 == 0 or k % 4 == 2.5: place(mus, drum_low() * perc * 0.8, t0)
            if k % 2 == 1: place(mus, drum_tek() * perc * 0.8, t0)
            t0 += beat / 2; k += 1
# final chord resolve
place(mus, pad_note(midi(62), 3.0) * 0.3, 62.0)

# ---------- Ducking driven by the VO ----------
rms = np.sqrt(lp(VO ** 2, 12, 1) + 1e-9)
thr = 0.03
duck = 1 - 0.78 * np.clip(rms / thr, 0, 1)
duck = lp(duck.astype(np.float32), 8, 1)           # smooth release
duck = np.clip(duck, 0.18, 1)
sfx_duck = 1 - 0.45 * (1 - duck) / 0.82           # SFX duck less, never cover words
sfx_duck = np.clip(sfx_duck, 0.55, 1)

music_gain = 0.55
# gentle arc: fade in first 1s, fade out last 0.6s
fade = np.ones(N); fade[:SR] = np.linspace(0, 1, SR); fade[-int(0.6 * SR):] = np.linspace(1, 0, int(0.6 * SR))
mix = VO * 1.0 + (mus * music_gain * duck + sfx * 0.9 * sfx_duck) * fade
peak = np.max(np.abs(mix))
mix = np.tanh(mix * 0.95) / np.tanh(0.95) if peak > 0.9 else mix
mix = mix / max(1e-9, np.max(np.abs(mix))) * 0.70   # final level: ~ -14 LUFS
stereo = np.stack([mix, mix], 1)
wavfile.write('public/audio/mix.wav', SR, (stereo * 32767).astype(np.int16))
wavfile.write('assets/music_sfx_only.wav', SR, (np.stack([(mus * music_gain + sfx * 0.9) * 0.5] * 2, 1) * 32767).astype(np.int16))
print('peak', float(np.max(np.abs(mix))), 'dur', len(mix) / SR)
# diagnostics: music+sfx level vs VO during speech
speech = rms > thr
m_rms = np.sqrt(np.mean(((mus * music_gain * duck + sfx * 0.9 * sfx_duck) * fade)[speech] ** 2))
v_rms = np.sqrt(np.mean(VO[speech] ** 2))
print('speech: VO rms %.1f dBFS, music+sfx rms %.1f dBFS, VO-over-bed %.1f dB' % (20*np.log10(v_rms), 20*np.log10(m_rms), 20*np.log10(v_rms/m_rms)))
